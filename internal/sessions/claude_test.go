func TestLoadClaudeDir(t *testing.T) {
	dir := t.TempDir()
	logs := filepath.Join(dir, "-repo-x")
	if err := os.MkdirAll(logs, 0o755); err != nil {
		t.Fatal(err)
	}
	write := func(name, content string) {
		if err := os.WriteFile(filepath.Join(logs, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	line := `{"type":"user","message":{"role":"user","content":"prompt %s"},"timestamp":"2026-10-13T09:0%d:00.000Z","sessionId":"%s"}`
	write("first.jsonl", "not json at all\n")
	write("second.jsonl", "{\"type\":\"user\",\"message\":{\"role\":\"user\",\"content\":\"second\"},\"timestamp\":\"2026-10-13T09:05:00.000Z\",\"sessionId\":\"s2\"}\n")
	write("third.jsonl", fmt.Sprintf(line, "third", 2, "s3"))
	// Same session ID as third: must be deduplicated.
	write("dupe.jsonl", fmt.Sprintf(line, "dupe", 2, "s3"))
	// Subdirectories hold artifacts, not logs — must be skipped.
	if err := os.MkdirAll(filepath.Join(logs, "s3.dir"), 0o755); err != nil {
		t.Fatal(err)
	}
	write(filepath.Join("s3.dir", "nested.jsonl"), fmt.Sprintf(line, "nested", 2, "s9"))

	byID := make(map[string]Session)
	if err := loadClaudeDir(logs, "/repo", byID); err != nil {
		t.Fatalf("loadClaudeDir() error = %v", err)
	}
	if len(byID) != 2 {
		t.Fatalf("loaded %d sessions, want 2 (bad log skipped, dupe deduped, subdir ignored): %#v", len(byID), byID)
	}
	if s := byID["s2"]; s.FirstPrompt != "second" {
		t.Errorf("s2 FirstPrompt = %q", s.FirstPrompt)
	}
	if s := byID["s3"]; s.FirstPrompt != "prompt dupe" {
		// Files are read in lexical order, so dupe.jsonl is seen first.
		t.Errorf("s3 FirstPrompt = %q, want deterministic dedupe on session ID", s.FirstPrompt)
	}
}

