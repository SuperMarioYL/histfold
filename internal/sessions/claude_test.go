func TestParseClaudeSessionCommandIntent(t *testing.T) {
	// A slash-command-driven session has no typed prompt; the invocation is
	// the best available intent.
	log := `{"type":"user","message":{"role":"user","content":"<command-message>deploy</command-message>\n<command-name>/deploy</command-name>\n<command-args>--fresh prod</command-args>"},"timestamp":"2026-10-13T09:00:00.000Z","sessionId":"cmd1"}
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /x"}]},"timestamp":"2026-10-13T09:00:10.000Z","sessionId":"cmd1"}
`
	s := mustParse(t, log, "")
	if s.FirstPrompt != "/deploy --fresh prod" {
		t.Errorf("FirstPrompt = %q, want the command invocation", s.FirstPrompt)
	}
}

