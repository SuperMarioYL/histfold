func TestRelativize(t *testing.T) {
	tests := []struct {
		path, root, want string
		ok               bool
	}{
		{"/repo/a/b.go", "/repo", "a/b.go", true},
		{"a/b.go", "/repo", "a/b.go", true},
		{"/outside/a.go", "/repo", "", false},
		{"/repo/../escape/a.go", "/repo", "", false},
		{"", "/repo", "", false},
	}
	for _, tt := range tests {
		got, ok := relativize(tt.path, tt.root)
		if ok != tt.ok || got != tt.want {
			t.Errorf("relativize(%q, %q) = (%q, %v), want (%q, %v)", tt.path, tt.root, got, ok, tt.want, tt.ok)
		}
	}
}
